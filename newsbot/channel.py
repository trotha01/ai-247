"""Channel manifest math for the Day 1 uploader: a Python port of the swap reference in worker/src/playlist.js
(`layout`, `indexAt`, `tagsUpTo`, `eras`, `tagsBeforeEras`, `nextSwapStart`, `swapDseq`). Contract:
docs/MANIFEST-SWAP.md. Pure functions, no I/O. tests/test_publish.py checks them against vectors generated by the
JS reference (worker/test/fixtures/swap-v3-golden.json).

A root manifest.json carries `epoch` (fixed forever), `segment_seconds`, `blocks`, `cycle_start_k` (global segment
number at which its cycle[0] plays), `cycle_start_dseq` (EXT-X-DISCONTINUITY-SEQUENCE at that point), `prev` (the
manifest it replaced) and `loop_from`: the blocks before index `loop_from` (fresh bulletins) play once from
`cycle_start_k`, the blocks from `loop_from` on (slate + replays) loop until a newer manifest takes over. The Worker
plays `prev` for k < cycle_start_k, so a swap never changes a segment number a client has already seen.
"""
from __future__ import annotations

import math

# Must equal EPOCH in worker/wrangler.toml (the Worker's fallback). Set once; never change it after launch.
EPOCH = 1793000000
SEGMENT_SECONDS = 6
MARGIN = 10  # segments of lead (60 s): Worker manifest cache 10 s + R2 propagation + 5-segment client window


def layout(manifest: dict) -> tuple[list[dict], set[int], int]:
    """Flatten blocks -> (segments, block-start indexes, loop_at). Accepts the Day 0 shape ({segments:[{file,duration}]}).
    loop_at = first local index of the loop region (block `loop_from` among the non-empty blocks); 0 = whole cycle loops."""
    blocks = manifest.get("blocks") or [{"id": "main", "segments": manifest.get("segments", [])}]
    segs, starts, block_starts = [], set(), []
    for b in blocks:
        if not b.get("segments"):
            continue
        starts.add(len(segs))
        block_starts.append(len(segs))
        for s in b["segments"]:
            segs.append({"uri": s.get("uri", s.get("file")), "duration": float(s["duration"])})
    if not segs:
        raise ValueError("manifest has no segments")
    if any(not s["duration"] > 0 for s in segs):
        raise ValueError("bad segment duration")
    loop_from = manifest.get("loop_from", 0)
    if not isinstance(loop_from, int) or isinstance(loop_from, bool) or loop_from < 0 or loop_from >= len(block_starts):
        raise ValueError("bad loop_from (nothing left to loop)")
    return segs, starts, block_starts[loop_from]


def index_at(c: int, n: int, loop_at: int = 0) -> int:
    """Local index played at offset c = k - cycle_start_k: the cycle once in order, then [loop_at, n) forever.
    Negative c (an unanchored oldest era before its start) extends the whole cycle backwards, as before."""
    if c < 0:
        return c % n
    if c < n:
        return c
    return loop_at + (c - n) % (n - loop_at)


def _tags_up_to(c: int, n: int, starts: set[int], loop_at: int = 0) -> int:
    """Discontinuity-tagged local positions in [0, c) under index_at. For negative c the legacy arithmetic (Math.floor
    for the quotient, truncated `%` for the remainder) is kept so an unanchored era extended backwards gives identical
    numbers to the Worker. Same numbers as before for loop_at 0."""
    if c < 0:
        return math.floor(c / n) * len(starts) + sum(1 for b in starts if b < math.fmod(c, n))
    if c <= n:
        return sum(1 for b in starts if b < c)
    m = n - loop_at
    tail = [b for b in starts if b >= loop_at]
    q, r = divmod(c - n, m)
    return len(starts) + q * len(tail) + sum(1 for b in tail if b - loop_at < r)


def _tagged_in(e: dict, lo: int, hi: int) -> int:
    if hi <= lo:
        return 0
    return (_tags_up_to(hi - e["start"], e["n"], e["starts"], e["loop_at"])
            - _tags_up_to(lo - e["start"], e["n"], e["starts"], e["loop_at"]))


def eras(manifest: dict) -> list[dict]:
    chain = []
    m = manifest
    while m:
        chain.insert(0, m)
        m = m.get("prev")
    out = []
    for m in chain:
        segs, starts, loop_at = layout(m)
        start = int(m.get("cycle_start_k", 0))
        if start < 0:
            raise ValueError("bad cycle_start_k")
        anchor = m.get("cycle_start_dseq")
        if anchor is not None and (not isinstance(anchor, int) or anchor < 0):
            raise ValueError("bad cycle_start_dseq")
        out.append({"start": start, "segs": segs, "starts": starts, "n": len(segs), "anchor": anchor, "loop_at": loop_at})
    for i in range(1, len(out)):
        if out[i]["start"] <= out[i - 1]["start"]:
            raise ValueError("cycle_start_k must increase along prev chain")
    for i, e in enumerate(out):
        if e["anchor"] is not None:
            e["base"] = e["anchor"]
        elif i == 0:
            e["base"] = _tagged_in(e, 1, e["start"])
        else:
            p = out[i - 1]
            e["base"] = p["base"] + _tagged_in(p, max(p["start"], 1), e["start"])
    return out


def _era_for(es: list[dict], k: int) -> dict:
    e = es[0]
    for x in es:
        if x["start"] <= k:
            e = x
    return e


def era_segment(e: dict, k: int) -> dict:
    """What era `e` plays at global number k: {uri, duration, tag} (tag = EXT-X-DISCONTINUITY; never at k = 0)."""
    idx = index_at(k - e["start"], e["n"], e["loop_at"])
    s = e["segs"][idx]
    return {"uri": s["uri"], "duration": s["duration"], "tag": k > 0 and idx in e["starts"]}


def segment_at(manifest: dict, k: int) -> dict:
    return era_segment(_era_for(eras(manifest), k), k)


def tags_before_eras(first: int, es: list[dict]) -> int:
    """EXT-X-DISCONTINUITY-SEQUENCE for a window starting at `first` (segment 0 is never tagged)."""
    if first <= 0:
        return 0
    e = _era_for(es, first)
    if first < e["start"]:
        return 0
    return e["base"] + _tagged_in(e, max(e["start"], 1), first)


def live_k(now: float, epoch: int = EPOCH, seg_seconds: int = SEGMENT_SECONDS) -> int:
    return max(0, int(math.floor((now - epoch) / seg_seconds)))


def next_swap_start(cur: dict | None, publish_k: int, margin: int = MARGIN) -> int:
    """`cycle_start_k` for a manifest published while segment `publish_k` is live and `cur` is the manifest in R2:
    a pending cur keeps its start (it is replaced); a whole-cycle-loop cur (no loop_from) is swapped at its next loop
    boundary; a cur with fresh blocks is swapped at the end of its fresh region if that is still ahead, else right away
    (k + margin, inside its replay loop). Fresh footage that has not aired is never cut."""
    if not cur:
        return publish_k + margin
    e = eras(cur)[-1]
    want = publish_k + margin
    if e["start"] > want:
        return e["start"]  # cur has not started yet: replace it at its own boundary
    if e["loop_at"] == 0:
        return e["start"] + e["n"] * math.ceil((want - e["start"]) / e["n"])
    fresh_end = e["start"] + e["loop_at"]
    return fresh_end if want < fresh_end else want


def swap_dseq(cur: dict | None, start: int) -> int:
    return tags_before_eras(start, eras(cur)) if cur else 0


def pending(cur: dict | None, now: float, margin: int = MARGIN) -> bool:
    """True when the manifest in R2 has not started playing yet (and will not before our margin): it gets replaced."""
    if not cur:
        return False
    epoch = int(cur.get("epoch", EPOCH))
    return int(cur.get("cycle_start_k", 0)) > live_k(now, epoch) + margin


def fresh_blocks(cur: dict | None) -> list[dict]:
    """The blocks of `cur` that play once (before `loop_from`); [] for a whole-cycle-loop manifest."""
    if not cur:
        return []
    blocks = [b for b in cur.get("blocks", []) if b.get("segments")]
    return blocks[: int(cur.get("loop_from", 0) or 0)]


def next_manifest(cur: dict | None, blocks: list[dict], now: float, epoch: int = EPOCH, margin: int = MARGIN,
                  loop_from: int = 0) -> dict:
    """The root manifest to publish: `blocks` is the new cycle, `loop_from` the index of its first loop block (0 = the
    whole cycle loops, the Day 1 behaviour); continuity fields follow docs/MANIFEST-SWAP.md."""
    epoch = int(cur.get("epoch", epoch)) if cur else epoch  # the published epoch wins: it must never change
    k = live_k(now, epoch)
    start = next_swap_start(cur, k, margin)
    m = {"version": 3, "segment_seconds": SEGMENT_SECONDS, "epoch": epoch, "cycle_start_k": start,
         "cycle_start_dseq": swap_dseq(cur, start), "loop_from": int(loop_from), "blocks": blocks}
    layout(m)  # raises on an empty loop region or bad blocks before anything is written
    if cur:
        if int(cur.get("cycle_start_k", 0)) > k + margin:
            prev = cur.get("prev")  # cur never started: it is replaced, its predecessor stays the live one
        else:
            prev = {k2: v for k2, v in cur.items() if k2 != "prev"}
        if prev:
            m["prev"] = prev
    return m
